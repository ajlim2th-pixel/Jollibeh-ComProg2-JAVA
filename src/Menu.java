public void generateReceipt() {
String body = "";

double currenttotal = 0.00;
java.util.HashMap<String, Integer> counts = new java.util.HashMap<>();
java.util.HashMap<String, Double> prices = new java.util.HashMap<>();

for (int i = 0; i < itemNames.size(); i++) {
    String name1 = itemNames.get(i);
    double price1 = itemPrices.get(i);
    
    counts.put(name1, counts.getOrDefault(name1, 0) + 1);
    prices.put(name1, price1);
    
    
}
for (String name : counts.keySet()){
    int qty = counts.get(name);
    double unitPrice = prices.get(name);
    double subtotal = qty * unitPrice;
    
   body += String.format("%-16s %-9d ₱%.2f\n", name, qty, subtotal);
   currenttotal += subtotal;
   
}
LocalDateTime now = LocalDateTime.now();
DateTimeFormatter formatter = DateTimeFormatter.ofPattern("EEEE, MMM dd hh:mm a");

String formattedDate = now.format(formatter);
    String centered = String.format("%15s%s", " ", Dinein.orderType);
    String header = 
          "              JULLIBEH           \n"
        + "      Bulacan State University       \n"
        + "  Date/Time: " +formattedDate + "\n"
        + centered +"\n"
        + "----------------------------------\n"
        + "Item            Qty        Price  \n"
        + "----------------------------------\n";
    
    
    double cash = Double.parseDouble(payment.getText());
   double change1 = cash - total;
   

    String footer = 
          "----------------------------------\n"
        + "TOTAL: ₱" + String.format("%.2f", total) + "\n"
        + "CASH: ₱" + String.format("%.2f", cash) + "\n"
        + "CHANGE: ₱" + String.format("%.2f", change1) + "\n"
        + "----------------------------------\n"
        + "      THANK YOU FOR CHOOSING US!         ";

    receipt.setText(header + body + footer);
}
    
